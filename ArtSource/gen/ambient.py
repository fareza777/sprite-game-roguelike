def main(out):
    rgb = {k: tuple(int(v[i:i + 2], 16) for i in (1, 3, 5)) for k, v in L.items()}
    w = len(MOTES) * 2 * 8
    px = [[(0, 0, 0, 0)] * w for _ in range(8)]
    for b, frames in enumerate(MOTES):
        for f, rows in enumerate(frames):
            for y, row in enumerate(rows):
                for x, ch in enumerate(row):
                    if ch != ".":
                        px[y][(b * 2 + f) * 8 + x] = rgb[ch] + (255,)
    pngio.write(out, w, 8, px)
    print(out, w, "x 8")


if __name__ == "__main__":
    main(sys.argv[1])
